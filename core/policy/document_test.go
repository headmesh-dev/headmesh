// TestAppendDocumentMatchesEncodingJSON holds the reflection-free renderer to json.MarshalIndent byte for byte:
// nil versus empty lists and maps, the omitempty fields, sorted map keys and every escaping rule (quotes,
// backslashes, HTML characters, control characters, U+2028 and U+2029, invalid UTF-8).
func TestAppendDocumentMatchesEncodingJSON(t *testing.T) {
	rapid.Check(t, func(rt *rapid.T) {
		d := genDocument(rt)
		want, err := json.MarshalIndent(d, "", "  ")
		if err != nil {
			rt.Fatal(err)
		}
		if got := appendDocument(nil, d); string(got) != string(want) {
			rt.Fatalf("appendDocument differs from encoding/json\n got: %q\nwant: %q", got, want)
		}
	})
}

// TestRenderBodyIsTheIndentedDocument checks render's body against encoding/json after normalising, and that
// the full bytes are the header followed by that body.
func TestRenderBodyIsTheIndentedDocument(t *testing.T) {
	rapid.Check(t, func(rt *rapid.T) {
		d := genDocument(rt)
		full, body, sum := render("hs1", d)
		d.normalise()
		want, err := json.MarshalIndent(d, "", "  ")
		if err != nil {
			rt.Fatal(err)
		}
		if string(body) != string(want) {
			rt.Fatalf("body differs from encoding/json\n got: %q\nwant: %q", body, want)
		}
		header := "// Generated by Headmesh policy compiler v" + CompilerVersion + " for cell \"hs1\".\n" +
			"// Do not edit: Headmesh owns this policy and overwrites manual changes.\n"
		if string(full) != header+string(want)+"\n" {
			rt.Fatalf("full bytes are not header + body + newline: %q", full)
		}
		if len(sum) != 64 {
			rt.Fatalf("digest %q is not hex SHA-256", sum)
		}
	})
}

var trickyStrings = []string{
	"", "tag:hm-o-acme", "u0@", "tcp:22", `a"b`, `back\slash`, "<script>&</script>", "tab\there", "nl\n",
	"\x00\x1f\x7f", "  ", "é漢🙂", "\xff\xfe", "a\xc3", "�",
}

func genJSONString(t *rapid.T, label string) string {
	return rapid.OneOf(
		rapid.SampledFrom(trickyStrings),
		rapid.String(),
		rapid.Map(rapid.SliceOfN(rapid.Byte(), 0, 8), func(b []byte) string { return string(b) }),
	).Draw(t, label)
}

// genList returns nil, an empty list or one to three items, since encoding/json renders the three differently.
func genList[T any](t *rapid.T, label string, item func(*rapid.T) T) []T {
	switch rapid.IntRange(0, 2).Draw(t, label+"-kind") {
	case 0:
		return nil
	case 1:
		return []T{}
	default:
		return rapid.SliceOfN(rapid.Custom(item), 1, 3).Draw(t, label)
	}
}

func genStrings(t *rapid.T, label string) []string {
	return genList(t, label, func(t *rapid.T) string { return genJSONString(t, "s") })
}

func genDocument(t *rapid.T) Document {
	var d Document
	switch rapid.IntRange(0, 2).Draw(t, "tagOwners-kind") {
	case 1:
		d.TagOwners = map[string][]string{}
	case 2:
		d.TagOwners = map[string][]string{}
		for range rapid.IntRange(1, 4).Draw(t, "tagOwners-n") {
			d.TagOwners[genJSONString(t, "owner")] = genStrings(t, "owners")
		}
	}
	d.Grants = genList(t, "grants", func(t *rapid.T) GrantRule {
		return GrantRule{Src: genStrings(t, "src"), Dst: genStrings(t, "dst"), IP: genStrings(t, "ip")}
	})
	d.SSH = genList(t, "ssh", func(t *rapid.T) SSHRule {
		return SSHRule{
			Action: genJSONString(t, "action"), Src: genStrings(t, "src"), Dst: genStrings(t, "dst"),
			Users: genStrings(t, "users"),
		}
	})
	d.Tests = genList(t, "tests", func(t *rapid.T) PolicyTest {
		return PolicyTest{Src: genJSONString(t, "src"), Accept: genStrings(t, "accept"), Deny: genStrings(t, "deny")}
	})
	return d
}

package policy

import (
	"bytes"
	"crypto/sha256"
	"encoding/hex"
	"encoding/json"
	"fmt"
	"slices"
	"strings"

	"github.com/tailscale/hujson"
)

// CompilerVersion is embedded in every rendered document so a cell can report which compiler produced its
// active policy.
const CompilerVersion = "1"

// Document is the subset of the Headscale v0.29 policy format Headmesh emits. Legacy "acls" are never emitted:
// "grants" is always present (an empty list denies everything; omitting both would allow everything).
type Document struct {
	TagOwners map[string][]string `json:"tagOwners"`
	Grants    []GrantRule         `json:"grants"`
	SSH       []SSHRule           `json:"ssh,omitempty"`
	Tests     []PolicyTest        `json:"tests,omitempty"`
}

// GrantRule is one entry of the "grants" list.
type GrantRule struct {
	Src []string `json:"src"`
	Dst []string `json:"dst"`
	IP  []string `json:"ip"`
}

// SSHRule is one entry of the "ssh" list.
type SSHRule struct {
	Action string   `json:"action"`
	Src    []string `json:"src"`
	Dst    []string `json:"dst"`
	Users  []string `json:"users"`
}

// PolicyTest is a Headscale policy test; Headscale rejects the whole policy if any test fails.
type PolicyTest struct {
	Src    string   `json:"src"`
	Accept []string `json:"accept,omitempty"`
	Deny   []string `json:"deny,omitempty"`
}

// Compiled is a rendered policy ready to send to a cell.
type Compiled struct {
	HuJSON   []byte
	SHA256   string
	Document Document
	Stats    Stats
}

// Stats summarises a compiled policy for logs and metrics.
type Stats struct {
	Orgs, Devices, Rules, Grants, PlatformRules, Tags, Tests int
}

func (d *Document) normalise() {
	if d.TagOwners == nil {
		d.TagOwners = map[string][]string{}
	}
	if d.Grants == nil {
		d.Grants = []GrantRule{}
	}
	for i := range d.Grants {
		d.Grants[i].Src = sortedUnique(d.Grants[i].Src)
		d.Grants[i].Dst = sortedUnique(d.Grants[i].Dst)
		d.Grants[i].IP = sortedUnique(d.Grants[i].IP)
	}
	type keyed struct {
		key string
		g   GrantRule
	}
	ks := make([]keyed, len(d.Grants))
	for i, g := range d.Grants {
		ks[i] = keyed{key: g.key(), g: g}
	}
	slices.SortFunc(ks, func(a, b keyed) int { return strings.Compare(a.key, b.key) })
	ks = slices.CompactFunc(ks, func(a, b keyed) bool { return a.key == b.key })
	d.Grants = d.Grants[:0]
	for _, k := range ks {
		d.Grants = append(d.Grants, k.g)
	}
	for i := range d.SSH {
		d.SSH[i].Src = sortedUnique(d.SSH[i].Src)
		d.SSH[i].Dst = sortedUnique(d.SSH[i].Dst)
		d.SSH[i].Users = sortedUnique(d.SSH[i].Users)
	}
	slices.SortFunc(d.SSH, func(a, b SSHRule) int {
		return strings.Compare(strings.Join(a.Src, ",")+"|"+strings.Join(a.Dst, ","), strings.Join(b.Src, ",")+"|"+strings.Join(b.Dst, ","))
	})
	for i := range d.Tests {
		d.Tests[i].Accept = sortedUnique(d.Tests[i].Accept)
		d.Tests[i].Deny = sortedUnique(d.Tests[i].Deny)
	}
	slices.SortFunc(d.Tests, func(a, b PolicyTest) int { return strings.Compare(a.Src, b.Src) })
}

func (g GrantRule) key() string {
	return strings.Join(g.Src, ",") + "→" + strings.Join(g.Dst, ",") + "|" + strings.Join(g.IP, ",")
}

// render produces the canonical HuJSON bytes (a comment header followed by plain JSON), the JSON body alone,
// and the digest of the full bytes.
func render(cell string, doc Document) (full, body []byte, sum string, err error) {
	doc.normalise()
	body, err = json.MarshalIndent(doc, "", "  ")
	if err != nil {
		return nil, nil, "", fmt.Errorf("encode policy: %w", err)
	}
	var buf bytes.Buffer
	fmt.Fprintf(&buf, "// Generated by Headmesh policy compiler v%s for cell %q.\n", CompilerVersion, cell)
	buf.WriteString("// Do not edit: Headmesh owns this policy and overwrites manual changes.\n")
	buf.Write(body)
	buf.WriteByte('\n')
	digest := sha256.Sum256(buf.Bytes())
	return buf.Bytes(), body, hex.EncodeToString(digest[:]), nil
}

// ParseDocument reads a HuJSON policy (comments and trailing commas allowed) back into a Document. Unknown
// sections — including legacy "acls" — are rejected, as is a missing or null "grants" list, because Headscale
// treats a policy without grants or acls as allow-all.
func ParseDocument(b []byte) (Document, error) {
	std, err := hujson.Standardize(slices.Clone(b))
	if err != nil {
		return Document{}, fmt.Errorf("parse hujson: %w", err)
	}
	return parseJSON(std)
}

func parseJSON(std []byte) (Document, error) {
	dec := json.NewDecoder(bytes.NewReader(std))
	dec.DisallowUnknownFields()
	var doc Document
	if err := dec.Decode(&doc); err != nil {
		return Document{}, fmt.Errorf("decode policy (unknown sections are rejected): %w", err)
	}
	if dec.More() {
		return Document{}, fmt.Errorf("trailing data after policy document")
	}
	if doc.Grants == nil {
		return Document{}, fmt.Errorf(`policy has no "grants" list; Headscale would allow all traffic`)
	}
	return doc, nil
}

func sortedUnique(in []string) []string {
	if len(in) == 0 {
		return []string{}
	}
	out := slices.Clone(in)
	slices.Sort(out)
	return slices.Compact(out)
}

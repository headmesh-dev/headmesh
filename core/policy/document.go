// CompilerVersion is embedded in every rendered document so a cell can report which compiler produced its
// active policy.
const CompilerVersion = "1"

// Document is the subset of the Headscale v0.29 policy format Headmesh emits. Every tag a live device carries
// is declared in tagOwners even when no rule references it. Legacy "acls" are never emitted:
// "grants" is always present (an empty list denies everything; omitting both would allow everything).
type Document struct {
	TagOwners map[string][]string `json:"tagOwners"`
	Grants    []GrantRule         `json:"grants"`
	SSH       []SSHRule           `json:"ssh,omitempty"`
	Tests     []PolicyTest        `json:"tests,omitempty"`
}

// GrantRule is one entry of the "grants" list.
type GrantRule struct {
	Src []string `json:"src"`
	Dst []string `json:"dst"`
	IP  []string `json:"ip"`
}

// SSHRule is one entry of the "ssh" list.
type SSHRule struct {
	Action string   `json:"action"`
	Src    []string `json:"src"`
	Dst    []string `json:"dst"`
	Users  []string `json:"users"`
}

// PolicyTest is a Headscale policy test; Headscale rejects the whole policy if any test fails.
type PolicyTest struct {
	Src    string   `json:"src"`
	Accept []string `json:"accept,omitempty"`
	Deny   []string `json:"deny,omitempty"`
}

// Compiled is a rendered policy ready to send to a cell.
type Compiled struct {
	HuJSON   []byte
	SHA256   string
	Document Document
	Stats    Stats
}

// Stats summarises a compiled policy for logs and metrics.
type Stats struct {
	Orgs, Devices, Rules, Grants, PlatformRules, Tags, Tests int
}

// normalise sorts and de-duplicates every list in place, so the document must own its slices. The builder's
// document does: addGrant copies its inputs and every other list is built fresh.
func (d *Document) normalise() {
	if d.TagOwners == nil {
		d.TagOwners = map[string][]string{}
	}
	if d.Grants == nil {
		d.Grants = []GrantRule{}
	}
	for i := range d.Grants {
		d.Grants[i].Src = sortInPlace(d.Grants[i].Src)
		d.Grants[i].Dst = sortInPlace(d.Grants[i].Dst)
		d.Grants[i].IP = sortInPlace(d.Grants[i].IP)
	}
	type keyed struct {
		key string
		g   GrantRule
	}
	ks := make([]keyed, len(d.Grants))
	for i, g := range d.Grants {
		ks[i] = keyed{key: g.key(), g: g}
	}
	slices.SortFunc(ks, func(a, b keyed) int { return strings.Compare(a.key, b.key) })
	ks = slices.CompactFunc(ks, func(a, b keyed) bool { return a.key == b.key })
	d.Grants = d.Grants[:0]
	for _, k := range ks {
		d.Grants = append(d.Grants, k.g)
	}
	for i := range d.SSH {
		d.SSH[i].Src = sortInPlace(d.SSH[i].Src)
		d.SSH[i].Dst = sortInPlace(d.SSH[i].Dst)
		d.SSH[i].Users = sortInPlace(d.SSH[i].Users)
	}
	slices.SortFunc(d.SSH, func(a, b SSHRule) int {
		return strings.Compare(strings.Join(a.Src, ",")+"|"+strings.Join(a.Dst, ","), strings.Join(b.Src, ",")+"|"+strings.Join(b.Dst, ","))
	})
	for i := range d.Tests {
		d.Tests[i].Accept = sortInPlace(d.Tests[i].Accept)
		d.Tests[i].Deny = sortInPlace(d.Tests[i].Deny)
	}
	slices.SortFunc(d.Tests, func(a, b PolicyTest) int { return strings.Compare(a.Src, b.Src) })
}

func (g GrantRule) key() string {
	return strings.Join(g.Src, ",") + "→" + strings.Join(g.Dst, ",") + "|" + strings.Join(g.IP, ",")
}

// render produces the canonical HuJSON bytes (a comment header followed by plain JSON), the JSON body alone,
// and the digest of the full bytes.
func render(cell string, doc Document) (full, body []byte, sum string) {
	doc.normalise()
	full = fmt.Appendf(nil, "// Generated by Headmesh policy compiler v%s for cell %q.\n", CompilerVersion, cell)
	full = append(full, "// Do not edit: Headmesh owns this policy and overwrites manual changes.\n"...)
	start := len(full)
	full = appendDocument(full, doc)
	full = append(full, '\n')
	digest := sha256.Sum256(full)
	return full, full[start : len(full)-1], hex.EncodeToString(digest[:])
}

// appendDocument appends d exactly as json.MarshalIndent(d, "", "  ") would, without reflection.
// TestAppendDocumentMatchesEncodingJSON holds it to that byte for byte, and Compile still decodes the result
// with encoding/json before verifying it.
func appendDocument(b []byte, d Document) []byte {
	b = append(b, "{\n  \"tagOwners\": "...)
	switch {
	case d.TagOwners == nil:
		b = append(b, "null"...)
	case len(d.TagOwners) == 0:
		b = append(b, "{}"...)
	default:
		keys := slices.Sorted(maps.Keys(d.TagOwners))
		b = append(b, "{\n"...)
		for i, k := range keys {
			b = append(b, "    "...)
			b = appendString(b, k)
			b = append(b, ": "...)
			b = appendStrings(b, d.TagOwners[k], 2)
			b = appendSeparator(b, i, len(keys))
		}
		b = append(b, "  }"...)
	}
	b = append(b, ",\n  \"grants\": "...)
	b = appendList(b, d.Grants, func(b []byte, g GrantRule) []byte {
		b = appendField(b, "src", true)
		b = appendStrings(b, g.Src, 3)
		b = appendField(b, "dst", false)
		b = appendStrings(b, g.Dst, 3)
		b = appendField(b, "ip", false)
		return appendStrings(b, g.IP, 3)
	})
	if len(d.SSH) > 0 {
		b = append(b, ",\n  \"ssh\": "...)
		b = appendList(b, d.SSH, func(b []byte, r SSHRule) []byte {
			b = appendField(b, "action", true)
			b = appendString(b, r.Action)
			b = appendField(b, "src", false)
			b = appendStrings(b, r.Src, 3)
			b = appendField(b, "dst", false)
			b = appendStrings(b, r.Dst, 3)
			b = appendField(b, "users", false)
			return appendStrings(b, r.Users, 3)
		})
	}
	if len(d.Tests) > 0 {
		b = append(b, ",\n  \"tests\": "...)
		b = appendList(b, d.Tests, func(b []byte, t PolicyTest) []byte {
			b = appendField(b, "src", true)
			b = appendString(b, t.Src)
			if len(t.Accept) > 0 {
				b = appendField(b, "accept", false)
				b = appendStrings(b, t.Accept, 3)
			}
			if len(t.Deny) > 0 {
				b = appendField(b, "deny", false)
				b = appendStrings(b, t.Deny, 3)
			}
			return b
		})
	}
	return append(b, "\n}"...)
}

// appendList appends a list of objects at depth 1 (the document's top-level lists), one object per element.
// A nil list is null unless the field is omitempty, in which case the caller has already skipped it.
func appendList[T any](b []byte, list []T, fields func([]byte, T) []byte) []byte {
	if list == nil {
		return append(b, "null"...)
	}
	if len(list) == 0 {
		return append(b, "[]"...)
	}
	b = append(b, "[\n"...)
	for i, item := range list {
		b = append(b, "    {"...)
		b = fields(b, item)
		b = append(b, "\n    }"...)
		b = appendSeparator(b, i, len(list))
	}
	return append(b, "  ]"...)
}

// appendField starts a member of an object in one of the document's top-level lists (so at depth 3), preceded
// by a comma unless it's the first.
func appendField(b []byte, name string, first bool) []byte {
	if !first {
		b = append(b, ',')
	}
	b = append(b, "\n      \""...)
	b = append(b, name...)
	return append(b, "\": "...)
}

// appendStrings appends a string array whose opening bracket sits at depth.
func appendStrings(b []byte, list []string, depth int) []byte {
	if list == nil {
		return append(b, "null"...)
	}
	if len(list) == 0 {
		return append(b, "[]"...)
	}
	b = append(b, "[\n"...)
	for i, s := range list {
		b = appendIndent(b, depth+1)
		b = appendString(b, s)
		b = appendSeparator(b, i, len(list))
	}
	b = appendIndent(b, depth)
	return append(b, ']')
}

// appendSeparator ends element i of n: a comma unless it's the last, then a newline.
func appendSeparator(b []byte, i, n int) []byte {
	if i < n-1 {
		b = append(b, ',')
	}
	return append(b, '\n')
}

func appendIndent(b []byte, depth int) []byte {
	for range depth {
		b = append(b, "  "...)
	}
	return b
}

// appendString quotes s. Printable ASCII that encoding/json leaves alone is copied directly; anything else goes
// through encoding/json so escaping (HTML characters, control characters, invalid UTF-8) stays identical.
func appendString(b []byte, s string) []byte {
	for i := range len(s) {
		if c := s[i]; c < 0x20 || c > 0x7e || c == '"' || c == '\\' || c == '<' || c == '>' || c == '&' {
			quoted, _ := json.Marshal(s) // a string always encodes
			return append(b, quoted...)
		}
	}
	b = append(b, '"')
	b = append(b, s...)
	return append(b, '"')
}

// ParseDocument reads a HuJSON policy (comments and trailing commas allowed) back into a Document. Unknown
// sections — including legacy "acls" — are rejected, as is a missing or null "grants" list, because Headscale
// treats a policy without grants or acls as allow-all.
func ParseDocument(b []byte) (Document, error) {
	std, err := hujson.Standardize(slices.Clone(b))
	if err != nil {
		return Document{}, fmt.Errorf("parse hujson: %w", err)
	}
	return parseJSON(std)
}

func parseJSON(std []byte) (Document, error) {
	dec := json.NewDecoder(bytes.NewReader(std))
	dec.DisallowUnknownFields()
	var doc Document
	if err := dec.Decode(&doc); err != nil {
		return Document{}, fmt.Errorf("decode policy (unknown sections are rejected): %w", err)
	}
	if dec.More() {
		return Document{}, fmt.Errorf("trailing data after policy document")
	}
	if doc.Grants == nil {
		return Document{}, fmt.Errorf(`policy has no "grants" list; Headscale would allow all traffic`)
	}
	return doc, nil
}

func sortedUnique(in []string) []string {
	return sortInPlace(slices.Clone(in))
}

// sortInPlace sorts s and drops duplicates, reusing its backing array. Empty or nil comes back as an empty,
// non-nil slice, so it encodes as [] rather than null.
func sortInPlace(s []string) []string {
	if len(s) == 0 {
		return []string{}
	}
	slices.Sort(s)
	return slices.Compact(s)
}
